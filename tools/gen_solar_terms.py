"""Generate src/solar_terms.h (day-of-month of the 24 solar terms, 2000-2100).

Data source: lunar_python (astronomical algorithms, same results as the
Purple Mountain Observatory / Hong Kong Observatory published tables).

Usage:  python tools/gen_solar_terms.py
"""

import os

from lunar_python import Solar

NAMES = [
    "小寒", "大寒", "立春", "雨水", "惊蛰", "春分", "清明", "谷雨",
    "立夏", "小满", "芒种", "夏至", "小暑", "大暑", "立秋", "处暑",
    "白露", "秋分", "寒露", "霜降", "立冬", "小雪", "大雪", "冬至",
]

FIRST_YEAR = 2000
LAST_YEAR = 2100


def build_rows():
    rows = []
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        table = Solar.fromYmd(year, 7, 1).getLunar().getJieQiTable()
        days = []
        for index, name in enumerate(NAMES):
            # In lunar_python's table the current year's 冬至 is stored under the
            # pinyin alias DONG_ZHI, while "冬至" points at the previous year.
            key = "DONG_ZHI" if name == "冬至" else name
            term = table[key]
            assert term.getYear() == year, (year, name, term.toYmdHms())
            assert term.getMonth() == index // 2 + 1, (year, name, term.toYmdHms())
            days.append(term.getDay())
        rows.append(days)
    return rows


def main():
    rows = build_rows()

    lines = [
        "// Auto-generated by tools/gen_solar_terms.py using lunar_python.",
        "// Day-of-month of the 24 solar terms for years 2000..2100.",
        "// Row order: year - 2000. Column order:",
        "// 小寒 大寒 | 立春 雨水 | 惊蛰 春分 | 清明 谷雨 | 立夏 小满 | 芒种 夏至 |",
        "// 小暑 大暑 | 立秋 处暑 | 白露 秋分 | 寒露 霜降 | 立冬 小雪 | 大雪 冬至",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define SOLAR_TERM_FIRST_YEAR {FIRST_YEAR}",
        f"#define SOLAR_TERM_LAST_YEAR  {LAST_YEAR}",
        "",
        "static const uint8_t SOLAR_TERM_DAYS"
        "[SOLAR_TERM_LAST_YEAR - SOLAR_TERM_FIRST_YEAR + 1][24] = {",
    ]

    for year, days in zip(range(FIRST_YEAR, LAST_YEAR + 1), rows):
        values = ",".join("%2d" % day for day in days)
        lines.append("  {%s}, // %d" % (values, year))

    lines += [
        "};",
        "",
        "static const char *const SOLAR_TERM_NAMES[24] = {",
        '  "小寒","大寒","立春","雨水","惊蛰","春分","清明","谷雨",',
        '  "立夏","小满","芒种","夏至","小暑","大暑","立秋","处暑",',
        '  "白露","秋分","寒露","霜降","立冬","小雪","大雪","冬至"',
        "};",
    ]

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    output = os.path.join(root, "src", "solar_terms.h")
    with open(output, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")

    print("wrote", output, "years", len(rows))


if __name__ == "__main__":
    main()
